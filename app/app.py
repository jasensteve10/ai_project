@st.cache_data
def saved_answers():
    """Answers generated by Claude Haiku 4.5 in the archived evaluation run (no new calls)."""
    records = {json.loads(l)['id']: json.loads(l) for l in (ROOT / 'benchmarks/edan_2025_v1.jsonl').open()}
    out = {}
    for line in (SAVED_RUN / 'traces.jsonl').open():
        t = json.loads(line)
        out[(t['question_id'], t['condition'])] = {
            'question': records[t['question_id']]['question'], 'answerability': t.get('answerability'),
            'ok': t['executed'], 'status': t['status'], 'response': t.get('response'),
            'final_sql': t.get('final_sql'), 'columns': t.get('columns'), 'rows': t.get('rows'),
            'outcome': t['outcome'], 'success': t['success'], 'error': t.get('error'), 'stage': t.get('stage'),
            'context_ids': t.get('context_ids', []), 'condition': t['condition'], 'saved': True,
            'served_by': ['Claude Haiku 4.5']}
    return out


@st.cache_resource
def init_rag(version, condition):
    return ElectionRAG(condition)


def get_rag(condition):
    return init_rag(rag_fingerprint(condition), condition)


