# ---------------------------------------------------------------- rendering
def render_sources(sources):
    with st.expander(f'Contexte retrouvé · {len(sources)} fiches'):
        for card in sources:
            st.markdown(f"**{card['title']}** · `{card['id']}`")
            st.text(card['text'])


def render_result(out, compact=False):
    if out.get('saved') and not compact:
        st.caption(f"Réponse enregistrée (Claude Haiku 4.5, évaluation du 30/09/2026) · mode {SHORT[out['condition']]}"
                   f" · {OUTCOME_LABEL.get(out['outcome'], out['outcome'])}")
    if out.get('status') == 'search':
        st.info('Contexte que le modèle recevrait pour cette question. Les réponses SQL en direct sont désactivées ; '
                'essayez un exemple ci-dessus ou l’onglet « Réponses enregistrées ».')
    elif out.get('status') in {'unsupported', 'needs_clarification'}:
        st.info(out['response'])
    elif not out.get('ok'):
        st.error('Impossible de répondre à cette question.')
        st.caption(f"{out.get('stage', 'application')} : {(out.get('error') or 'erreur inconnue')[:300]}")
    else:
        df = pd.DataFrame(out['rows'], columns=out['columns'])
        if not compact:
            served = ', '.join(out.get('served_by') or []) or 'modèle'
            st.success(f"{len(df)} ligne(s) · {served}" + (' · réponse en cache' if out.get('cache_hit') else ''))
        st.dataframe(df, width='stretch', hide_index=True)
        if show_sql:
            st.code(out.get('final_sql') or '', language='sql', wrap_lines=compact)
    if compact:
        return
    sources = out.get('sources') or [rag.builder.by_id[c] for c in out.get('context_ids', []) if c in rag.builder.by_id]
    if sources:
        render_sources(sources)
    if out.get('fallback_used'):
        st.warning('Réponse produite par le modèle de secours Claude (API payante) : Gemini était indisponible.')


def answer(question, cond, example_id=None):
    """Live answer when allowed; otherwise the saved answer for examples, or retrieval-only context."""
    try:
        if LIVE:
            out = st.session_state.result_cache.query(question, rag_fingerprint(cond), get_rag(cond).run_query)
            return {**out, 'condition': cond}
        if example_id:
            return saved_answers()[(example_id, cond)]
        return {'ok': True, 'status': 'search', 'sources': get_rag(cond).search(question), 'condition': cond}
    except Exception as exc:
        return {'ok': False, 'stage': 'application', 'error': str(exc), 'condition': cond}


def ask(question, cond, example_id=None):
    st.session_state.messages.append({'role': 'user', 'content': f"{question}  \n*mode : {MODES[cond]}*"})
    with st.spinner('Recherche dans les sources…'):
        st.session_state.messages.append({'role': 'assistant', 'result': answer(question, cond, example_id)})


